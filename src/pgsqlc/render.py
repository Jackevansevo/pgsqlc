"""Render the IR as Python source by building ``ast`` trees.

Source text is only produced by ``ast.unparse`` and then ``ruff format``.
Imported names are used unqualified (``from dataclasses import dataclass``).
One that clashes with a generated name is aliased with a leading underscore,
which generated fields, parameters and classes may never start with.
"""

import ast
import subprocess
import sys
from dataclasses import dataclass, field

from pgsqlc.ir import (
    NO_ROWS_ERROR,
    Builtin,
    Command,
    CompositeRef,
    EnumDef,
    EnumRef,
    ListOf,
    ModelResult,
    Nullable,
    OneOf,
    Package,
    Param,
    PyType,
    Query,
    QueryModule,
    RecordDef,
    RowResult,
)

HEADER = "Code generated by pgsqlc. DO NOT EDIT."
_MODELS_MODULE = ".models"
_POOL_MODULE = "asyncpg.pool"


@dataclass(slots=True)
class _Imports:
    """Names one generated file imports, bound once the body is built.

    Each reference is a placeholder ``ast.Name``. ``bind`` gives every imported
    name its plain spelling unless the body already uses it, in which case the
    import is aliased with a leading underscore (generated names never start
    with ``_``, so the alias is always free).
    """

    in_models: bool
    refs: dict[tuple[str, str], list[ast.Name]] = field(default_factory=dict)

    def attr(self, module: str, name: str) -> ast.expr:
        node = ast.Name(name)
        self.refs.setdefault((module, name), []).append(node)
        return node

    def model(self, name: str) -> ast.expr:
        if self.in_models:
            return ast.Name(name)
        return self.attr(_MODELS_MODULE, name)

    def bind(self, body: list[ast.stmt]) -> list[ast.stmt]:
        """Choose each import's local name and return the import statements."""
        placeholders = {id(n) for nodes in self.refs.values() for n in nodes}
        taken = _bound_names(body, placeholders)
        locals_: dict[tuple[str, str], str] = {}
        for module, name in sorted(self.refs):
            local = name
            if local in taken:
                local = "_" + name
            if local in taken:
                local = "_" + module.strip(".").replace(".", "_") + "_" + name
            taken.add(local)
            locals_[module, name] = local
            for node in self.refs[module, name]:
                node.id = local
        by_module: dict[str, list[ast.alias]] = {}
        for (module, name), local in sorted(locals_.items()):
            alias = ast.alias(name, None if local == name else local)
            by_module.setdefault(module, []).append(alias)
        return [
            ast.ImportFrom(
                module.lstrip("."), names, len(module) - len(module.lstrip("."))
            )
            for module, names in by_module.items()
        ]


def _bound_names(body: list[ast.stmt], placeholders: set[int]) -> set[str]:
    """Every identifier the body defines or references, except import refs."""
    names: set[str] = set()
    for node in ast.walk(ast.Module(body, [])):
        if isinstance(node, ast.Name) and id(node) not in placeholders:
            names.add(node.id)
        elif isinstance(node, ast.arg):
            names.add(node.arg)
        elif isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            names.add(node.name)
    return names


def _union(items: list[ast.expr]) -> ast.expr:
    result = items[0]
    for item in items[1:]:
        result = ast.BinOp(result, ast.BitOr(), item)
    return result


def _flatten(t: PyType) -> list[PyType]:
    if isinstance(t, OneOf):
        return [leaf for item in t.items for leaf in _flatten(item)]
    if isinstance(t, Nullable):
        inner = [leaf for leaf in _flatten(t.inner) if leaf != Builtin(None, "None")]
        return [*inner, Builtin(None, "None")]
    return [t]


def _annotation(t: PyType, imp: _Imports, *, param: bool) -> ast.expr:
    if isinstance(t, OneOf | Nullable):
        return _union([_annotation(leaf, imp, param=param) for leaf in _flatten(t)])
    if isinstance(t, ListOf):
        container = (
            imp.attr("collections.abc", "Sequence") if param else ast.Name("list")
        )
        return ast.Subscript(container, _annotation(t.item, imp, param=param))
    if isinstance(t, EnumRef | CompositeRef):
        return imp.model(t.name)
    if t.module is None:
        return ast.Constant(None) if t.name == "None" else ast.Name(t.name)
    base = imp.attr(t.module, t.name)
    if not t.args:
        return base
    args = [_annotation(a, imp, param=param) for a in t.args]
    return ast.Subscript(base, args[0] if len(args) == 1 else ast.Tuple(args))


def _if_not_none(value: ast.expr, converted: ast.expr) -> ast.expr:
    return ast.IfExp(
        ast.Compare(value, [ast.Is()], [ast.Constant(None)]),
        ast.Constant(None),
        converted,
    )


def _map_list(value: ast.expr, item: ast.expr | None, var: str) -> ast.expr | None:
    if item is None:
        return None
    return ast.ListComp(item, [ast.comprehension(ast.Name(var), value, [], 0)])


def _decode(
    t: PyType, value: ast.expr, imp: _Imports, depth: int = 0
) -> ast.expr | None:
    """Expression converting an asyncpg value to ``t``; ``None`` if no-op."""
    if isinstance(t, Nullable):
        inner = _decode(t.inner, value, imp, depth)
        return None if inner is None else _if_not_none(value, inner)
    if isinstance(t, EnumRef):
        return ast.Call(imp.model(t.name), [value], [])
    if isinstance(t, CompositeRef):
        return ast.Call(ast.Attribute(imp.model(t.name), "from_record"), [value], [])
    if isinstance(t, ListOf):
        var = f"item{depth}"
        return _map_list(value, _decode(t.item, ast.Name(var), imp, depth + 1), var)
    return None


def _encode(
    t: PyType, value: ast.expr, imp: _Imports, depth: int = 0
) -> ast.expr | None:
    """Expression converting a parameter value for asyncpg; ``None`` if no-op."""
    if isinstance(t, Nullable):
        inner = _encode(t.inner, value, imp, depth)
        return None if inner is None else _if_not_none(value, inner)
    if isinstance(t, CompositeRef):
        return ast.Call(imp.attr("dataclasses", "astuple"), [value], [])
    if isinstance(t, ListOf):
        var = f"item{depth}"
        return _map_list(value, _encode(t.item, ast.Name(var), imp, depth + 1), var)
    return None


def _docstring(text: str) -> ast.stmt:
    return ast.Expr(ast.Constant(text))


def _enum_class(e: EnumDef, imp: _Imports) -> ast.stmt:
    body: list[ast.stmt] = [
        ast.Assign([ast.Name(m.name)], ast.Constant(m.value)) for m in e.members
    ]
    return ast.ClassDef(
        e.name, [imp.attr("enum", "StrEnum")], [], body or [ast.Pass()], []
    )


def _record_class(r: RecordDef, imp: _Imports) -> ast.stmt:
    fields: list[ast.stmt] = [
        ast.AnnAssign(ast.Name(f.name), _annotation(f.type, imp, param=False), None, 1)
        for f in r.fields
    ]
    record = ast.Name("r")
    values = [
        ast.keyword(
            f.name,
            _decode(f.type, ast.Subscript(record, ast.Constant(i)), imp)
            or ast.Subscript(record, ast.Constant(i)),
        )
        for i, f in enumerate(r.fields)
    ]
    from_record = ast.FunctionDef(
        "from_record",
        ast.arguments(
            [],
            [ast.arg("cls"), ast.arg("r", imp.attr("asyncpg", "Record"))],
            None,
            [],
            [],
            None,
            [],
        ),
        [ast.Return(ast.Call(ast.Name("cls"), [], values))],
        [ast.Name("classmethod")],
        imp.attr("typing", "Self"),
    )
    decorator = ast.Call(
        imp.attr("dataclasses", "dataclass"),
        [],
        [
            ast.keyword(k, ast.Constant(value=True))
            for k in ("frozen", "slots", "kw_only")
        ],
    )
    return ast.ClassDef(r.name, [], [], [*fields, from_record], [decorator])


def _conn_annotation(imp: _Imports) -> ast.expr:
    return _union(
        [
            imp.attr("asyncpg", "Connection"),
            imp.attr("asyncpg", "Pool"),
            imp.attr(_POOL_MODULE, "PoolConnectionProxy"),
        ]
    )


def _await_call(method: str, q: Query, imp: _Imports) -> ast.expr:
    args: list[ast.expr] = [ast.Name(q.constant_name)]
    args.extend(
        _encode(p.type, ast.Name(p.name), imp) or ast.Name(p.name) for p in q.params
    )
    return ast.Await(ast.Call(ast.Attribute(ast.Name("conn"), method), args, []))


def _result_class(q: Query, imp: _Imports) -> ast.expr:
    if isinstance(q.result, ModelResult):
        return imp.model(q.result.name)
    if isinstance(q.result, RowResult):
        return ast.Name(q.result.row.name)
    msg = f"internal error: query {q.name} has no result"
    raise TypeError(msg)


def _function_body(q: Query, imp: _Imports) -> tuple[list[ast.stmt], ast.expr]:
    if q.command == Command.ONE:
        cls = _result_class(q, imp)
        row = ast.Name("row")
        call = ast.Call(ast.Attribute(cls, "from_record"), [row], [])
        body: list[ast.stmt] = [
            ast.Assign([ast.Name("row")], _await_call("fetchrow", q, imp)),
            ast.Return(_if_not_none(row, call)),
        ]
        return body, _union([_result_class(q, imp), ast.Constant(None)])
    if q.command == Command.SINGLE:
        cls = _result_class(q, imp)
        row = ast.Name("row")
        error = ast.Call(
            imp.model(NO_ROWS_ERROR),
            [ast.Constant(f"query {q.name} returned no rows")],
            [],
        )
        body = [
            ast.Assign([ast.Name("row")], _await_call("fetchrow", q, imp)),
            ast.If(
                ast.Compare(row, [ast.Is()], [ast.Constant(None)]),
                [ast.Raise(error, None)],
                [],
            ),
            ast.Return(ast.Call(ast.Attribute(cls, "from_record"), [row], [])),
        ]
        return body, _result_class(q, imp)
    if q.command == Command.MANY:
        cls = _result_class(q, imp)
        item = ast.Call(ast.Attribute(cls, "from_record"), [ast.Name("r")], [])
        comp = ast.ListComp(
            item,
            [ast.comprehension(ast.Name("r"), _await_call("fetch", q, imp), [], 0)],
        )
        return [ast.Return(comp)], ast.Subscript(
            ast.Name("list"), _result_class(q, imp)
        )
    if q.command == Command.EXECROWS:
        status = _await_call("execute", q, imp)
        last = ast.Subscript(
            ast.Call(ast.Attribute(status, "rpartition"), [ast.Constant(" ")], []),
            ast.Constant(2),
        )
        return [ast.Return(ast.Call(ast.Name("int"), [last], []))], ast.Name("int")
    return [ast.Expr(_await_call("execute", q, imp))], ast.Constant(None)


def _param_arg(p: Param, imp: _Imports) -> ast.arg:
    return ast.arg(p.name, _annotation(p.type, imp, param=True))


def _function(q: Query, imp: _Imports) -> ast.stmt:
    body, returns = _function_body(q, imp)
    if q.doc:
        body.insert(0, _docstring(q.doc))
    args = ast.arguments(
        [],
        [ast.arg("conn", _conn_annotation(imp))],
        None,
        [_param_arg(p, imp) for p in q.params],
        [None for _ in q.params],
        None,
        [],
    )
    return ast.AsyncFunctionDef(q.function_name, args, body, [], returns)


def _sql_block(sql: str) -> str | None:
    """``sql`` as a triple-quoted literal, or ``None`` if it should stay inline.

    The block gains a leading and trailing newline, which Postgres ignores.
    """
    if "\n" not in sql or not all(c.isprintable() or c in "\n\t" for c in sql):
        return None
    body = sql.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return f'"""\n{body}\n"""'


def _module_source(
    doc: str,
    imp: _Imports,
    body: list[ast.stmt],
    blocks: dict[str, str] | None = None,
) -> str:
    """Unparse the module, then swap each placeholder in ``blocks`` for its text.

    ``ast.unparse`` writes every string with ``repr``; only docstrings get
    triple quotes, so multi-line SQL is spliced in afterwards.
    """
    module = ast.Module([_docstring(doc), *imp.bind(body), *body], [])
    source = ast.unparse(ast.fix_missing_locations(module))
    for placeholder, text in (blocks or {}).items():
        source = source.replace(repr(placeholder), text, 1)
    return _format(source)


def _no_rows_error_class() -> ast.stmt:
    doc = "Raised when a :single query returns no rows."
    return ast.ClassDef(
        NO_ROWS_ERROR, [ast.Name("LookupError")], [], [_docstring(doc)], []
    )


def _models_source(package: Package) -> str:
    imp = _Imports(in_models=True)
    body: list[ast.stmt] = [_no_rows_error_class()]
    body.extend(_enum_class(e, imp) for e in package.enums)
    body.extend(_record_class(r, imp) for r in (*package.composites, *package.tables))
    return _module_source(
        f"{HEADER}\n\nShared enums, composite types and table models.\n", imp, body
    )


def _query_module_source(m: QueryModule) -> str:
    imp = _Imports(in_models=False)
    body: list[ast.stmt] = []
    blocks: dict[str, str] = {}
    for q in m.queries:
        final = imp.attr("typing", "Final")
        sql = ast.Constant(q.sql)
        if (block := _sql_block(q.sql)) is not None:
            placeholder = f"\x00pgsqlc-sql-{len(blocks)}\x00"
            blocks[placeholder] = block
            sql = ast.Constant(placeholder)
        body.append(ast.AnnAssign(ast.Name(q.constant_name), final, sql, 1))
        if isinstance(q.result, RowResult):
            body.append(_record_class(q.result.row, imp))
        body.append(_function(q, imp))
    return _module_source(f"{HEADER}\n\nSource: {m.source_name}\n", imp, body, blocks)


def _ruff(args: list[str], source: str) -> str:
    command = [sys.executable, "-m", "ruff", *args, "--isolated"]
    result = subprocess.run(
        [*command, "--target-version", "py315", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        msg = f"internal error: ruff {args[0]} failed: {result.stderr}"
        raise RuntimeError(msg)
    return result.stdout


def _format(source: str) -> str:
    """Sort imports into isort groups, then apply ruff's formatting."""
    imports_sorted = _ruff(["check", "--select", "I", "--fix", "--quiet"], source)
    return _ruff(["format"], imports_sorted)


def render(package: Package) -> dict[str, str]:
    """Map each output file name to its source."""
    files = {
        "__init__.py": _format(
            ast.unparse(ast.Module([_docstring(f"{HEADER}\n")], []))
        ),
        "models.py": _models_source(package),
    }
    for m in package.modules:
        files[f"{m.module_name}.py"] = _query_module_source(m)
    return files
